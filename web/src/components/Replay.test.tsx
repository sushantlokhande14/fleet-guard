import { render, screen } from "@testing-library/react";
import { afterEach, describe, expect, it, vi } from "vitest";

import { failureDetail } from "../test/failure";
import { routeFetch } from "../test/fixtures";
import Replay, { eventMarkers, nearest } from "./Replay";

afterEach(() => vi.unstubAllGlobals());

const series = (offset: number) => ({
  t: [0, 0.1, 0.2, 0.3],
  v: [10, 10.5 + offset, 11, 11.5],
  cte: [0, 0.01, 0.02 + offset, 0.01],
  steer: [0, 0.01, 0, -0.01],
  a: [0, 0.5, 0.5, 0.2],
  planner_latency_ms: [30, 31, 95, 30],
  gt_gap: [null, null, 40, 39],
});

describe("Replay helpers", () => {
  it("finds the nearest sample", () => {
    expect(nearest([0, 0.1, 0.2, 0.3], 0.14)).toBe(1);
    expect(nearest([0, 0.1, 0.2, 0.3], 0.16)).toBe(2);
    expect(nearest([0, 0.1, 0.2, 0.3], 9)).toBe(3);
    expect(nearest([0, 0.1, 0.2, 0.3], -1)).toBe(0);
  });

  it("marks candidate events but not routine latency jitter", () => {
    const m = eventMarkers(failureDetail.candidate);
    expect(m.map((x) => x.label.split(" ")[0])).toEqual(["phantom_object", "steer_oscillation"]);
  });
});

describe("Replay", () => {
  it("draws six charts for both builds and a readout at the cursor", async () => {
    vi.stubGlobal("fetch", vi.fn(routeFetch({
      "/api/failures/41/telemetry": { source: "replayed", columns: [], baseline: series(0), candidate: series(0.5) },
      "/api/failures/41/scenario": { id: "s", family: "s_curve", geometry: { route: [[0, 0], [10, 0]], lane_width: 3.6 } },
    })));
    render(<Replay failureId={41} candidate={failureDetail.candidate} cursor={0.2} onCursor={() => {}} />);
    expect(await screen.findByText(/regenerated by fgsim/)).toBeInTheDocument();
    expect(await screen.findByRole("img", { name: "trajectories" })).toBeInTheDocument();
    expect(screen.getAllByRole("img")).toHaveLength(7);
    expect(screen.getByTestId("readout")).toHaveTextContent("planner 95 / 95 ms");
  });
});
