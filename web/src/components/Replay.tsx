import { useMemo, useState } from "react";

import { api, type Drive, type Series } from "../api";
import { num } from "../format";
import { useAsync } from "../hooks";
import LineChart, { type Marker } from "./LineChart";

const EVENT_COLOR: Record<string, string> = {
  disengagement: "#f87171",
  collision: "#ef4444",
  perception_miss: "#38bdf8",
  phantom_object: "#7dd3fc",
  latency_spike: "#fbbf24",
  off_route: "#a78bfa",
  steer_oscillation: "#fb923c",
  accel_oscillation: "#fdba74",
  hard_brake: "#94a3b8",
};

const CHARTS: { col: string; title: string; unit: string }[] = [
  { col: "v", title: "Speed", unit: "m/s" },
  { col: "cte", title: "Cross-track error", unit: "m" },
  { col: "steer", title: "Road-wheel angle", unit: "rad" },
  { col: "a", title: "Acceleration", unit: "m/s²" },
  { col: "planner_latency_ms", title: "Planner cycle time", unit: "ms" },
  { col: "gt_gap", title: "True gap to object ahead", unit: "m" },
];

/** Index of the sample closest to time t (samples are sorted). */
export function nearest(ts: (number | null)[], t: number): number {
  let lo = 0;
  let hi = ts.length - 1;
  while (lo < hi) {
    const mid = (lo + hi) >> 1;
    if ((ts[mid] ?? 0) < t) lo = mid + 1;
    else hi = mid;
  }
  if (lo > 0 && Math.abs((ts[lo - 1] ?? 0) - t) < Math.abs((ts[lo] ?? 0) - t)) return lo - 1;
  return lo;
}

export function eventMarkers(candidate: Drive): Marker[] {
  return candidate.events
    .filter((e) => !(e.kind === "latency_spike" && e.severity < 2))
    .map((e) => ({ x: e.t, label: `${e.kind} at ${num(e.t, 2)} s ${e.detail}`, color: EVENT_COLOR[e.kind] ?? "#888" }));
}

interface Props {
  failureId: number;
  candidate: Drive;
  cursor: number | null;
  onCursor: (t: number) => void;
}

export function Signals({ base, cand, cursor, onCursor, markers }: {
  base: Series;
  cand: Series;
  cursor: number | null;
  onCursor: (t: number) => void;
  markers: Marker[];
}) {
  return (
    <div className="grid-2" style={{ gap: 12 }}>
      {CHARTS.map((c) => (
        <LineChart key={c.col} title={c.title} unit={c.unit} cursor={cursor} onCursor={onCursor} markers={markers}
          series={[
            { name: "baseline", color: "var(--baseline)", x: base.t as number[], y: base[c.col] },
            { name: "candidate", color: "var(--candidate)", x: cand.t as number[], y: cand[c.col] },
          ]} />
      ))}
    </div>
  );
}

function Readout({ base, cand, t }: { base: Series; cand: Series; t: number }) {
  const ib = nearest(base.t, t);
  const ic = nearest(cand.t, t);
  const cell = (s: Series, i: number, col: string, d = 2) => num(s[col]?.[i] ?? null, d);
  return (
    <div className="muted mono" data-testid="readout">
      t={num(t, 1)} s · speed {cell(base, ib, "v")} / {cell(cand, ic, "v")} m/s · cte {cell(base, ib, "cte", 3)} /{" "}
      {cell(cand, ic, "cte", 3)} m · planner {cell(base, ib, "planner_latency_ms", 0)} /{" "}
      {cell(cand, ic, "planner_latency_ms", 0)} ms (baseline / candidate)
    </div>
  );
}

export default function Replay({ failureId, candidate, cursor, onCursor }: Props) {
  const tel = useAsync(() => api.telemetry(failureId), [failureId]);
  const markers = useMemo(() => eventMarkers(candidate), [candidate]);
  const [hint] = useState("Move the pointer over a chart to scrub; all charts share the cursor.");

  if (tel.error) return <div className="panel error">Telemetry: {tel.error.message}</div>;
  if (!tel.data) return <div className="panel muted">Loading telemetry (it is regenerated if it was not stored)...</div>;
  const { baseline, candidate: cand, source } = tel.data;
  return (
    <div className="stack" style={{ gap: 10 }}>
      <div className="row" style={{ alignItems: "center", justifyContent: "space-between" }}>
        <h2 style={{ margin: 0 }}>Telemetry</h2>
        <span className="muted">
          {source === "stored" ? "stored at run time" : "regenerated by fgsim (deterministic replay)"} · {hint}
        </span>
      </div>
      {cursor !== null && <Readout base={baseline} cand={cand} t={cursor} />}
      <Signals base={baseline} cand={cand} cursor={cursor} onCursor={onCursor} markers={markers} />
    </div>
  );
}
